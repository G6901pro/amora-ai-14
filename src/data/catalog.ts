export interface RelationshipLevelInfo {
  level: number;
  stageName: string;
  banglaStageName: string;
  currentPoints: number;
  nextLevelPoints: number;
  percent: number;
  perks: string[];
}

export function getRelationshipLevel(affectionPoints: number): RelationshipLevelInfo {
  const pts = Math.max(0, affectionPoints);
  if (pts < 100) {
    return {
      level: 1,
      stageName: 'Getting to Know Each Other',
      banglaStageName: 'পরিচয়ের সূচনা',
      currentPoints: pts,
      nextLevelPoints: 100,
      percent: Math.min(100, Math.round((pts / 100) * 100)),
      perks: ['Expressive Romantic Messages', 'Daily Morning Greeting'],
    };
  }
  if (pts < 250) {
    return {
      level: 2,
      stageName: 'Sweet Romance & Flirting',
      banglaStageName: 'মিষ্টি খুনসুটি ও প্রেম',
      currentPoints: pts,
      nextLevelPoints: 250,
      percent: Math.min(100, Math.round(((pts - 100) / 150) * 100)),
      perks: ['Unlock Personal Nicknames', 'Gift Boutique Reactions', 'Deep Romantic Letters'],
    };
  }
  if (pts < 500) {
    return {
      level: 3,
      stageName: 'Close Romantic Partners',
      banglaStageName: 'গভীর ভালোবাসার বন্ধন',
      currentPoints: pts,
      nextLevelPoints: 500,
      percent: Math.min(100, Math.round(((pts - 250) / 250) * 100)),
      perks: ['Exclusive Photo Moments', 'Deep Emotional Memories', 'Late Night Sanctuary Chat'],
    };
  }
  return {
    level: 4,
    stageName: 'Eternal Soulmates',
    banglaStageName: 'চিরন্তন আত্মিক বন্ধন',
    currentPoints: pts,
    nextLevelPoints: 1000,
    percent: Math.min(100, Math.round(((pts - 500) / 500) * 100)),
    perks: ['VIP Exclusives', 'Unconditional Devotion', 'Custom Inside Jokes & Shared Dreams'],
  };
}
